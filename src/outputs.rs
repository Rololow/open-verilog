//! The outputs derived from the memory maps: the C defines, the device tree nodes, and the documentation. Each one
//! reads the devices as the elaborator placed them, so the addresses and interrupt numbers are the checked ones.

use std::collections::HashMap;

use crate::elab::env::MapDev;

/// The identifier of a struct in SystemVerilog: its lower-case name, its other characters (an instance's values) as
/// single underscores: `box_4_8` for the instance `Box<4, 8>`.
fn ident(struct_name: &str) -> String {
    let mut out = String::new();
    for c in struct_name.to_lowercase().chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c);
        } else if !out.ends_with('_') {
            out.push('_');
        }
    }
    out.trim_matches('_').to_string()
}

/// The name of the packed type of a struct: `pixel_t` for `Pixel`, `pkt_t` for `Pkt_t` (no second `_t`).
fn type_name(struct_name: &str) -> String {
    let name = ident(struct_name);
    if name.ends_with("_t") {
        name
    } else {
        format!("{name}_t")
    }
}

/// The SystemVerilog type of a packed struct: `pixel_pkg::pixel_t` for `Pixel`.
pub fn typedef_name(struct_name: &str) -> String {
    format!("{}_pkg::{}", ident(struct_name), type_name(struct_name))
}

/// The package of a packed struct: its typedef, one member per field, the first field the most significant.
pub fn struct_package(struct_name: &str, fields: &[(String, i64, i64)], field_types: &HashMap<String, String>) -> String {
    let mut out = format!("package {}_pkg;\n  typedef struct packed {{\n", ident(struct_name));
    for (name, msb, lsb) in fields {
        // a struct field has the package type of its struct; the other members are vectors of their own width (their
        // position in the struct is not their size)
        if let Some(key) = field_types.get(name) {
            out.push_str(&format!("    {} {name};\n", typedef_name(key)));
            continue;
        }
        let dims = if msb > lsb { format!(" [{}:0]", msb - lsb) } else { String::new() };
        out.push_str(&format!("    logic{dims} {name};\n"));
    }
    out.push_str(&format!("  }} {};\nendpackage\n\n", type_name(struct_name)));
    out
}

/// One field of an exported struct: its name, width in bits, offset in bytes, signedness and description.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RecordField {
    pub name: String,
    pub width: i64,
    pub offset: i64,
    pub signed: bool,
    pub desc: String,
}

/// An exported struct: one memory layout, shared by the hardware and the software.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Record {
    pub name: String,
    pub desc: String,
    pub size: i64,
    pub fields: Vec<RecordField>,
}

/// `camelCase` -> `CAMEL_CASE`, as the C names of the structs.
fn c_name(n: &str) -> String {
    let chars: Vec<char> = n.chars().collect();
    let mut out = String::new();
    for (i, ch) in chars.iter().enumerate() {
        if ch.is_uppercase() && i > 0 && (chars[i - 1].is_lowercase() || (i + 1 < chars.len() && chars[i + 1].is_lowercase())) {
            out.push('_');
        }
        out.extend(ch.to_uppercase());
    }
    out
}

fn c_type(f: &RecordField) -> String {
    format!("{}{}_t", if f.signed { "int" } else { "uint" }, f.width)
}

/// The C header of the exported structs: the struct, its size and each field's offset, checked at compile time.
pub fn record_c_header(records: &[Record]) -> String {
    let mut out: Vec<String> = [
        "/* Generated by ovc from the exported structs: do not edit. */",
        "#pragma once",
        "#ifdef __KERNEL__",
        "#include <linux/types.h>",
        "#else",
        "#include <stdint.h>",
        "#endif",
        "",
    ]
    .iter()
    .map(|s| s.to_string())
    .collect();
    for r in records {
        let up = c_name(&r.name);
        out.push(if r.desc.is_empty() { format!("/* {} ({} bytes) */", r.name, r.size) } else { format!("/* {}: {} ({} bytes) */", r.name, r.desc, r.size) });
        out.push("typedef struct {".into());
        for f in &r.fields {
            let note = if f.desc.is_empty() { String::new() } else { format!("  /* {} */", f.desc) };
            out.push(format!("  {} {};{note}", c_type(f), f.name));
        }
        out.push(format!("}} {};", r.name));
        out.push(format!("#define {up}_SIZE {}u", r.size));
        for f in &r.fields {
            out.push(format!("#define {up}_{}_OFFSET {}u", f.name.to_uppercase(), f.offset));
        }
        out.extend([
            "#ifdef __cplusplus".into(),
            format!("static_assert(sizeof({0}) == {1}, \"{0}: layout of the hardware\");", r.name, r.size),
            "#else".into(),
            format!("_Static_assert(sizeof({0}) == {1}, \"{0}: layout of the hardware\");", r.name, r.size),
            "#endif".into(),
        ]);
        out.push(String::new());
    }
    out.join("\n")
}

/// A Python module with one class per struct: `pack`, `unpack` and `words`, with the layout of the C struct.
pub fn record_python_module(records: &[Record]) -> String {
    let mut out: Vec<String> = [
        "\"\"\"Generated by ovc from the exported structs: do not edit.\"\"\"",
        "import struct",
        "",
        "",
        "class Record:",
        "    \"\"\"pack(**fields) -> bytes (missing fields are 0), unpack(bytes) -> dict, words(**fields) -> 32-bit",
        "    words (little endian), as the hardware reads them.\"\"\"",
        "    FIELDS = ()",
        "    FORMAT = \"<\"",
        "    SIZE = 0",
        "",
        "    @classmethod",
        "    def pack(cls, **values):",
        "        unknown = set(values) - set(cls.FIELDS)",
        "        if unknown:",
        "            raise ValueError(f'{cls.__name__} has no field {sorted(unknown)[0]}')",
        "        return struct.pack(cls.FORMAT, *(values.get(f, 0) for f in cls.FIELDS))",
        "",
        "    @classmethod",
        "    def unpack(cls, data):",
        "        return dict(zip(cls.FIELDS, struct.unpack(cls.FORMAT, bytes(data[:cls.SIZE]))))",
        "",
        "    @classmethod",
        "    def words(cls, **values):",
        "        b = cls.pack(**values)",
        "        return [int.from_bytes(b[i:i + 4], 'little') for i in range(0, len(b), 4)]",
        "",
    ]
    .iter()
    .map(|s| s.to_string())
    .collect();
    for r in records {
        let code: String = r
            .fields
            .iter()
            .map(|f| {
                let c = match f.width {
                    8 => 'B',
                    16 => 'H',
                    32 => 'I',
                    _ => 'Q',
                };
                if f.signed { c.to_ascii_lowercase() } else { c }
            })
            .collect();
        let names: Vec<String> = r.fields.iter().map(|f| format!("'{}'", f.name)).collect();
        let offsets: Vec<String> = r.fields.iter().map(|f| format!("'{}': {}", f.name, f.offset)).collect();
        out.extend([
            String::new(),
            format!("class {}(Record):", r.name),
            format!("    \"\"\"{}\"\"\"", if r.desc.is_empty() { &r.name } else { &r.desc }),
            format!("    FIELDS = ({},)", names.join(", ")),
            format!("    FORMAT = \"<{code}\""),
            format!("    SIZE = {}", r.size),
            format!("    OFFSETS = {{{}}}", offsets.join(", ")),
        ]);
    }
    out.join("\n") + "\n"
}

/// The documentation of the exported structs: one table each.
pub fn record_markdown(records: &[Record]) -> String {
    let mut out: Vec<String> = Vec::new();
    for r in records {
        out.push(if r.desc.is_empty() { format!("## {} ({} bytes)", r.name, r.size) } else { format!("## {} ({} bytes) — {}", r.name, r.size, r.desc) });
        out.extend(["".into(), "| Offset | Field | Bits | Description |".into(), "|---|---|---|---|".into()]);
        for f in &r.fields {
            out.push(format!("| {} | {} | {}{} | {} |", f.offset, f.name, if f.signed { "s" } else { "u" }, f.width, f.desc));
        }
        out.push(String::new());
    }
    out.join("\n")
}

/// `(map name, description, devices)` of each memory map.
pub type Maps = [(String, String, Vec<MapDev>)];

/// C defines: `<MAP>_<DEV>_BASE`, `_SIZE` and `_IRQ` for each device.
pub fn memmap_c_header(maps: &Maps) -> String {
    let mut out = vec!["/* Generated by ovc from the memory maps: do not edit. */".to_string(), "#pragma once".to_string(), String::new()];
    for (name, desc, devices) in maps {
        let up = name.to_uppercase();
        out.push(if desc.is_empty() { format!("/* {name} */") } else { format!("/* {name}: {desc} */") });
        for d in devices {
            let note = if d.desc.is_empty() { String::new() } else { format!("  /* {} */", d.desc) };
            out.push(format!("#define {up}_{}_BASE 0x{:08x}u{note}", d.name, d.base));
            out.push(format!("#define {up}_{}_SIZE 0x{:x}u", d.name, d.size));
            if let Some(irq) = d.irq {
                out.push(format!("#define {up}_{}_IRQ {irq}u", d.name));
            }
        }
        out.push(String::new());
    }
    out.join("\n")
}

/// Device tree nodes for the devices with a `compatible`: include them inside the bus node of a `.dts`.
pub fn memmap_dts(maps: &Maps) -> String {
    let mut out = vec!["/* Generated by ovc from the memory maps: do not edit. */".to_string()];
    for (_, _, devices) in maps {
        for d in devices.iter().filter(|d| !d.compatible.is_empty()) {
            out.push(String::new());
            out.push(format!("{}@{:x} {{", d.name.to_lowercase(), d.base));
            out.push(format!("  compatible = \"{}\";", d.compatible));
            out.push(format!("  reg = <0x{:x} 0x{:x}>;", d.base, d.size));
            if let Some(irq) = d.irq {
                out.push("  interrupt-parent = <&plic>;".to_string());
                out.push(format!("  interrupts = <{irq}>;"));
            }
            for p in d.dt.split(';').map(str::trim).filter(|p| !p.is_empty()) {
                out.push(format!("  {p};"));
            }
            out.push("};".to_string());
        }
    }
    out.join("\n") + "\n"
}

/// The documentation of the memory maps: one table per map.
pub fn memmap_markdown(maps: &Maps) -> String {
    let mut out: Vec<String> = Vec::new();
    for (name, desc, devices) in maps {
        out.push(if desc.is_empty() { format!("## Memory map {name}") } else { format!("## Memory map {name} — {desc}") });
        out.extend(["".into(), "| Device | Base | Size | IRQ | Compatible | Description |".into(), "|---|---|---|---|---|---|".into()]);
        for d in devices {
            let irq = d.irq.map_or(String::new(), |i| i.to_string());
            out.push(format!("| {} | 0x{:08x} | 0x{:x} | {irq} | {} | {} |", d.name, d.base, d.size, d.compatible, d.desc));
        }
        out.push(String::new());
    }
    out.join("\n")
}

use crate::elab::isa::{FieldLayout, FormatInfo, IsaInfo};

/// The Python repr of a list of `(name, start, width, count, array)` tuples, as the encoder's FIELDS table.
fn field_spec(f: &FormatInfo) -> String {
    let items: Vec<String> = f
        .fields
        .iter()
        .map(|x| format!("('{}', {}, {}, {}, {})", x.name, x.start, x.width, x.count.unwrap_or(1), if x.count.is_some() { "True" } else { "False" }))
        .collect();
    format!("[{}]", items.join(", "))
}

/// The bits of a field as the documentation writes them: `msb:lsb` for a field of more than one bit.
fn bits_of(start: i64, total: i64) -> String {
    if total > 1 {
        format!("{}:{start}", start + total - 1)
    } else {
        start.to_string()
    }
}

fn max_len(isa: &IsaInfo) -> i64 {
    isa.formats.iter().map(|f| f.length).max().unwrap_or(isa.opcode_bits)
}

/// The SV package of each instruction set: the opcode of each format, its length and the start and length of its
/// fields, and the table of the length of each opcode.
pub fn isa_sv_package(isas: &[IsaInfo]) -> String {
    let mut out: Vec<String> = vec!["// Generated by ovc from the isa definitions: do not edit.".into(), String::new()];
    for isa in isas {
        out.push(format!("package {}_isa_pkg;", isa.name.to_lowercase()));
        out.push(format!("  localparam int OPCODE_L = {};", isa.opcode_bits));
        out.push(format!("  localparam int MAX_INSTR_LEN = {};", max_len(isa)));
        for f in &isa.formats {
            let n = f.name.to_uppercase();
            let desc = if f.desc.is_empty() { String::new() } else { format!(": {}", f.desc) };
            out.push(format!("  // {}{desc}", f.name));
            out.push(format!("  localparam int {n}_OPCODE = {};", f.code));
            out.push(format!("  localparam int {n}_L = {};", f.length));
            for x in &f.fields {
                let p = format!("{n}_{}", x.name.to_uppercase());
                out.push(format!("  localparam int {p}_S = {};", x.start));
                out.push(format!("  localparam int {p}_L = {};", x.width * x.count.unwrap_or(1)));
                if let Some(count) = x.count {
                    out.push(format!("  localparam int {p}_W = {};", x.width));
                    out.push(format!("  localparam int {p}_N = {count};"));
                }
            }
        }
        let lut: Vec<String> = isa.lengths.iter().map(|v| v.to_string()).collect();
        out.push(format!("  localparam int OPCODE_LEN_LUT [0:{}] = '{{{}}};", isa.lengths.len() - 1, lut.join(", ")));
        out.push("endpackage".into());
        out.push(String::new());
    }
    out.join("\n")
}

/// The Python encoder and decoder of each instruction set: one class per format, with range checks.
pub fn isa_python_module(isas: &[IsaInfo]) -> String {
    let mut out: Vec<String> = vec!["\"\"\"Generated by ovc from the isa definitions: do not edit.\"\"\"".into(), String::new(), String::new()];
    for isa in isas {
        let desc = if isa.desc.is_empty() { isa.name.clone() } else { isa.desc.clone() };
        out.push(format!("class {}:", isa.name));
        out.push(format!("    \"\"\"{desc}\"\"\""));
        out.push(format!("    OPCODE_BITS = {}", isa.opcode_bits));
        out.push(format!("    MAX_LEN = {}", max_len(isa)));
        let lengths: Vec<String> = isa.lengths.iter().map(|v| v.to_string()).collect();
        out.push(format!("    LENGTHS = [{}]", lengths.join(", ")));
        out.push(String::new());
        for f in &isa.formats {
            let fdesc = if f.desc.is_empty() { f.name.clone() } else { f.desc.clone() };
            out.push(format!("    class {}:", f.name));
            out.push(format!("        \"\"\"{fdesc}\"\"\""));
            out.push(format!("        OPCODE = {}", f.code));
            out.push(format!("        LENGTH = {}", f.length));
            out.push(format!("        FIELDS = {}  # (name, start, width, count, array)", field_spec(f)));
            out.push(String::new());
        }
        let formats: Vec<String> = isa.formats.iter().map(|f| format!("{}: {}", f.code, f.name)).collect();
        out.push(format!("    FORMATS = {{{}}}", formats.join(", ")));
        out.push(String::new());
        out.extend(ENCODER.iter().map(|s| s.to_string()));
        out.push(String::new());
        out.push(String::new());
    }
    out.join("\n")
}

/// The encode and decode methods of every instruction-set class.
const ENCODER: &[&str] = &[
    "    @classmethod",
    "    def encode(cls, fmt, **values):",
    "        \"\"\"encode(Isa.LD, en=0b1011, mem_addr=17) -> int; array fields take a list.\"\"\"",
    "        word = fmt.OPCODE",
    "        unknown = set(values) - {f[0] for f in fmt.FIELDS}",
    "        if unknown:",
    "            raise ValueError(f'{fmt.__name__} has no field {sorted(unknown)[0]}')",
    "        for name, start, width, count, array in fmt.FIELDS:",
    "            v = values.get(name, [0] * count if array else 0)",
    "            items = list(v) if array else [v]",
    "            if len(items) != count:",
    "                raise ValueError(f'{fmt.__name__}.{name} takes {count} values')",
    "            for i, x in enumerate(items):",
    "                if not 0 <= x < 1 << width:",
    "                    raise ValueError(f'{fmt.__name__}.{name} = {x} does not fit in {width} bits')",
    "                word |= x << (start + i * width)",
    "        return word",
    "",
    "    @classmethod",
    "    def decode(cls, word):",
    "        \"\"\"int -> (format class, {field: value or list}).\"\"\"",
    "        fmt = cls.FORMATS.get(word & ((1 << cls.OPCODE_BITS) - 1))",
    "        if fmt is None:",
    "            raise ValueError(f'unknown opcode {word & ((1 << cls.OPCODE_BITS) - 1)}')",
    "        out = {}",
    "        for name, start, width, count, array in fmt.FIELDS:",
    "            items = [(word >> (start + i * width)) & ((1 << width) - 1) for i in range(count)]",
    "            out[name] = items if array else items[0]",
    "        return fmt, out",
];

/// The documentation of the instruction sets: the opcodes, then one table of fields per format.
pub fn isa_markdown(isas: &[IsaInfo]) -> String {
    let mut out: Vec<String> = Vec::new();
    for isa in isas {
        out.push(if isa.desc.is_empty() { format!("# {}", isa.name) } else { format!("# {} — {}", isa.name, isa.desc) });
        out.push(String::new());
        out.push(format!("Opcode: bits [{}:0]; longest instruction: {} bits.", isa.opcode_bits - 1, max_len(isa)));
        out.push(String::new());
        out.push("| opcode | format | bits | description |".into());
        out.push("|---|---|---|---|".into());
        for f in &isa.formats {
            out.push(format!("| {} | {} | {} | {} |", f.code, f.name, f.length, f.desc));
        }
        for f in &isa.formats {
            let desc = if f.desc.is_empty() { String::new() } else { format!(" — {}", f.desc) };
            out.push(String::new());
            out.push(format!("## {} (opcode {}, {} bits){desc}", f.name, f.code, f.length));
            out.push(String::new());
            out.push("| bits | field | description |".into());
            out.push("|---|---|---|".into());
            // the opcode is the first field of every format
            out.push(format!("| {} | opcode | operation |", bits_of(0, isa.opcode_bits)));
            for x in &f.fields {
                out.push(field_row(x));
            }
        }
        out.push(String::new());
    }
    out.join("\n")
}

fn field_row(x: &FieldLayout) -> String {
    let what = match x.count {
        Some(c) => format!("{}[{c}] ({} bits each)", x.name, x.width),
        None => x.name.clone(),
    };
    format!("| {} | {what} | {} |", bits_of(x.start, x.width * x.count.unwrap_or(1)), x.desc)
}
