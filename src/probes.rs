//! Debug probes, kept out of the design: one module per probe that prints when its condition holds on each rising
//! edge of the target's clock (at most `limit` times per instance), and a top module `ovc_probes` that binds it
//! into every instance. Probes are silent unless enabled with `+ovc_probe` or `+ovc_probe=<name>`.

use std::collections::BTreeSet;

use crate::ast::{Dir, Expr, Module, ProbeDef, Stmt};
use crate::emit::expr::{dims, dtype, expr};
use crate::error::{Error, Result};
use crate::pipeline::rewrite::{map_expr, map_stmt};

/// The probe modules and the bindings, for the target modules `(probe, concrete module name)`.
pub fn generate(probes: &[(ProbeDef, String)], modules: &[Module], file: &str) -> Result<String> {
    let mut out = String::from("// Generated by ovc: debug probes, bound into the design (add this file to a simulation to use them).\n");
    out += "// Enable with +ovc_probe (all) or +ovc_probe=<name>.\n\n";
    let mut binds = Vec::new();
    for (k, (probe, target)) in probes.iter().enumerate() {
        let module = modules
            .iter()
            .find(|m| &m.name == target)
            .ok_or_else(|| Error::new(format!("probe '{}': module '{}' not found", probe.name, probe.module), file, probe.pos.0, probe.pos.1))?;
        let (text, bind) = probe_module(k, probe, module, &probe.origin)?;
        out += &text;
        binds.push(bind);
    }
    out += "module ovc_probes;\n";
    for b in binds {
        out += &format!("  {b}\n");
    }
    out += "endmodule\n";
    Ok(out)
}

fn probe_module(k: usize, probe: &ProbeDef, m: &Module, file: &str) -> Result<(String, String)> {
    let fail = |msg: &str| Error::new(format!("probe '{}': {msg}", probe.name), file, probe.pos.0, probe.pos.1);
    // the signals of the module: ports, then declarations
    let mut signals: Vec<(String, crate::ast::DType, Vec<Expr>)> = m.ports.iter().map(|p| (p.name.clone(), p.dtype.clone(), p.dims.clone())).collect();
    for it in &m.items {
        if let crate::ast::ItemKind::Decl(d) = &it.kind {
            if !d.is_const {
                for x in &d.decls {
                    signals.push((x.name.clone(), d.dtype.clone(), x.dims.clone()));
                }
            }
        }
    }
    let clock = m.ports.iter().find(|p| p.name == "clk" && p.dir == Dir::Input).map(|_| "clk").ok_or_else(|| fail(&format!("'{}' has no clock input (clk) to sample on", m.name)))?;

    // the signals the probe reads
    let mut names = BTreeSet::new();
    names.insert(clock.to_string());
    let mut collect = |e: &Expr| -> std::result::Result<Option<Expr>, crate::pipeline::rewrite::Failure> {
        if let Expr::Ident(n, _) = e {
            names.insert(n.clone());
        }
        Ok(None)
    };
    let _ = map_expr(&probe.cond, &mut collect);
    if let Some(l) = &probe.limit {
        let _ = map_expr(l, &mut collect);
    }
    for s in &probe.body {
        let _ = map_stmt(s, &mut collect);
    }
    let mut ports = Vec::new();
    for n in &names {
        match signals.iter().find(|(s, _, _)| s == n) {
            Some((_, dt, dd)) => ports.push(format!("input {} {}{}", dtype(dt)?, n, dims(dd)?)),
            None if n == "$time" || n == "print" => {}
            None => return Err(fail(&format!("'{n}' is not a signal of '{}'", m.name))),
        }
    }

    let name = format!("ovc_probe_{k}");
    let cond = expr(&probe.cond, -1, false)?;
    let limit = match &probe.limit {
        Some(l) => format!(" && n < {}", expr(l, -1, false)?),
        None => String::new(),
    };
    let mut body = String::new();
    for s in &probe.body {
        stmt(s, probe, 3, &mut body, file)?;
    }
    let text = format!(
        "// probe {} ({file}:{}) on every instance of {}\nmodule {name} ({});\n  string sel;\n  bit on;\n  initial on = $test$plusargs(\"ovc_probe\") && (!$value$plusargs(\"ovc_probe=%s\", sel) || sel == \"{}\");\n  int n = 0;\n  always @(posedge {clock}) begin\n    if (on && ({cond}){limit}) begin\n      n++;\n{body}    end\n  end\nendmodule\n\n",
        probe.name,
        probe.pos.0,
        m.name,
        ports.join(", "),
        probe.name,
    );
    Ok((text, format!("bind {} {name} {name}_i (.*);", m.name)))
}

fn stmt(s: &Stmt, probe: &ProbeDef, ind: usize, out: &mut String, file: &str) -> Result<()> {
    let pad = "  ".repeat(ind);
    match s {
        Stmt::Block(stmts) => {
            for x in stmts {
                stmt(x, probe, ind, out, file)?;
            }
        }
        Stmt::If { cond, then, els } => {
            *out += &format!("{pad}if ({}) begin\n", expr(cond, -1, false)?);
            stmt(then, probe, ind + 1, out, file)?;
            if let Some(e) = els {
                *out += &format!("{pad}end else begin\n");
                stmt(e, probe, ind + 1, out, file)?;
            }
            *out += &format!("{pad}end\n");
        }
        Stmt::ExprStmt(Expr::Call(f, args)) if matches!(&**f, Expr::Ident(n, _) if n == "print") => {
            let fmt = match args.first() {
                Some(Expr::Num(text)) if text.starts_with('"') => text[1..text.len() - 1].to_string(),
                _ => return Err(Error::new(format!("probe '{}': print(\"format\", values...)", probe.name), file, probe.pos.0, probe.pos.1)),
            };
            let mut vals = vec!["$time".to_string()];
            for a in &args[1..] {
                vals.push(expr(a, -1, false)?);
            }
            *out += &format!("{pad}$display(\"[{}] %m t=%0t {fmt}\", {});\n", probe.name, vals.join(", "));
        }
        _ => {
            return Err(Error::new(
                format!("probe '{}': a probe holds print(...) and if statements", probe.name),
                file,
                probe.pos.0,
                probe.pos.1,
            ))
        }
    }
    Ok(())
}
