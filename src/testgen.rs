//! Testbenches from `test` blocks: one module per test, which drives its design with the statements of the test,
//! and a top module `ovc_tests` that runs them all and prints one PASS / FAIL line per test.
//!
//! Statements: `name = expr;` (inputs, bundle fields such as `s.aw.data.addr` included), `step;` / `step(n);`,
//! `reset;`, `expect(cond[, "message"]);`, `wait_until(cond[, max[, "message"]]);`, `print(...)`, `if`, `for i in a..b`
//! (unrolled), `val`, and the valid/ready commands `send(s.aw[, data])`, `send(s.aw, s.w)`, `recv(s.r[, cond])`. A
//! file-level `fn` whose body holds test statements is a test procedure, expanded where it is called. `dut.a.b`
//! reads an internal signal of the design.

use std::collections::HashMap;

use crate::ast::{Dir, Expr, Module, Port, Stmt, TestDef};
use crate::elab::{fold_expr, int_of, loop_values, Env};
use crate::emit::expr::{dims, dtype, expr};
use crate::error::{Error, Result};
use crate::pipeline::rewrite::map_expr;

/// Cycles a test may run before it is reported as timed out, when it does not say.
const DEFAULT_TIMEOUT: i64 = 100_000;
/// Test procedures nested in each other, at most.
const MAX_CALL_DEPTH: usize = 32;

/// Test procedures by name: their parameters and statements.
pub type Procs = HashMap<String, (Vec<String>, Vec<Stmt>)>;

/// The testbench of all tests: each `(test, design module)` pair, with the modules of the design, their
/// elaboration environments, and the test procedures.
pub fn generate(tests: &[(TestDef, String)], modules: &[Module], envs: &HashMap<String, Env>, procs: &Procs, file: &str) -> Result<String> {
    let mut out = String::from(
        "// Generated by ovc: the tests of the design, for any SystemVerilog simulator.\n// Top module: ovc_tests (one PASS / FAIL line per test, then a summary).\n`timescale 1ns/1ps\n\n",
    );
    for (k, (test, dut)) in tests.iter().enumerate() {
        let module = modules
            .iter()
            .find(|m| &m.name == dut)
            .ok_or_else(|| Error::new(format!("module '{}' not found for a test", test.module), file, test.pos.0, test.pos.1))?;
        let env = envs.get(dut).cloned().unwrap_or_default();
        out += &test_module(k, test, module, env, procs)?;
        out.push('\n');
    }
    out += "module ovc_tests;\n";
    for k in 0..tests.len() {
        out += &format!("  ovc_test_{k} t{k} ();\n");
    }
    out += "  int failed = 0;\n  event ovc_check_failed;   // triggered by the checks of the design ($error, protocol monitors)\n  int ovc_check_fails = 0;\n  always @(ovc_check_failed) ovc_check_fails++;\n  initial begin\n";
    if !tests.is_empty() {
        let all_done: Vec<String> = (0..tests.len()).map(|k| format!("t{k}.ovc_done")).collect();
        out += &format!("    wait ({});\n", all_done.join(" && "));
    }
    for (k, (test, _)) in tests.iter().enumerate() {
        let place = format!("{}:{}", test.origin, test.pos.0);
        out += &format!(
            "    if (t{k}.ovc_fails == 0) $display(\"PASS  {}  ({place})\");\n    else begin failed++; $display(\"FAIL  {}  ({place}): %0d check(s) failed\", t{k}.ovc_fails); end\n",
            test.name, test.name
        );
    }
    out += "    if (ovc_check_fails != 0) begin\n      failed++;\n      $display(\"FAIL  checks of the design failed (%0d time steps): see the errors above (their path names the test: ovc_tests.t<k>)\", ovc_check_fails);\n    end\n";
    out += &format!("    $display(\"ovc tests: %0d passed, %0d failed\", {} - failed, failed);\n", tests.len());
    out += "    if (failed) $fatal(1, \"ovc tests failed\");\n    $finish;\n  end\nendmodule\n";
    Ok(out)
}

/// The module of one test: the ports of the design, the clock and reset, and the statements of the test.
fn test_module(k: usize, test: &TestDef, m: &Module, env: Env, procs: &Procs) -> Result<String> {
    // the clock and the reset are the design's declared ones (`clock`, `reset`), the testbench drives them by name
    let clock = env.clock().is_some();
    // without a declared clock the testbench drives no clock, so the name is never written
    let clk = env.clock().unwrap_or_default().to_string();
    let reset = env.reset().map(|r| (r.name.clone(), r.low));
    let mut t = Writer { lines: Vec::new(), module: m, env, procs, clock, clk: clk.clone(), reset, test, binds: Vec::new(), dirty: true, at: String::new(), calls: Vec::new() };
    for p in &m.ports {
        if p.dir == Dir::Input && p.name != clk {
            t.w(&if p.dims.is_empty() { format!("{} = '0;", p.name) } else { format!("{} = '{{default: '0}};", p.name) });
        }
    }
    t.do_reset();
    t.run(&test.body)?;
    let timeout = match &test.timeout {
        Some(e) => int_of(&fold_expr(e, &Env::default())).unwrap_or(DEFAULT_TIMEOUT),
        None => DEFAULT_TIMEOUT,
    };
    let origin = &test.origin;
    let mut out = format!("// test \"{}\" ({origin}:{})\nmodule ovc_test_{k};\n", test.name, test.pos.0);
    for p in &m.ports {
        out += &format!("  {} {}{};\n", dtype(&p.dtype)?, p.name, dims(&p.dims)?);
    }
    out += "  int ovc_fails = 0;\n  bit ovc_done = 0;\n  string ovc_at = \"\";\n  bit ovc_taken [8];\n";
    out += &format!("  {} dut (.*);\n", m.name);
    if clock {
        out += &format!("  initial {clk} = 0;\n  always #5 {clk} = ~{clk};\n");
    }
    out += "  initial begin\n";
    for l in &t.lines {
        out += &format!("    {l}\n");
    }
    out += "    ovc_done = 1;\n  end\n";
    let wait = if clock { format!("repeat ({timeout}) @(posedge {clk})") } else { format!("#{}", 10 * timeout) };
    out += &format!(
        "  initial begin {wait}; if (!ovc_done) begin ovc_fails++; ovc_done = 1;\n    $display(\"  FAIL {origin}:{} [{}] timeout after {timeout} cycles, at %s\", ovc_at); end end\nendmodule\n",
        test.pos.0, test.name
    );
    Ok(out)
}

/// `((|(c)) !== 1'b1)`: the condition does not hold, unknown values included.
fn not_true(cond: &str) -> String {
    format!("((|({cond})) !== 1'b1)")
}

struct Writer<'a> {
    lines: Vec<String>,
    module: &'a Module,
    env: Env,
    procs: &'a Procs,
    clock: bool,
    /// The name of the design's clock, as declared (the testbench drives the port of that name).
    clk: String,
    reset: Option<(String, bool)>,
    test: &'a TestDef,
    /// Names bound while the statements run: procedure arguments, loop indices, `val`s.
    binds: Vec<(String, Expr)>,
    /// Inputs were changed: the combinational logic needs a moment before anything is read.
    dirty: bool,
    at: String,
    /// The test procedures being expanded: name and the line of the call.
    calls: Vec<(String, usize)>,
}

impl Writer<'_> {
    fn w(&mut self, text: &str) {
        self.lines.push(text.to_string());
    }

    fn fail(&self, what: &str, line: usize) -> Error {
        Error::new(format!("test \"{}\": {what}", self.test.name), &self.test.origin, line.max(self.test.pos.0), self.test.pos.1)
    }

    /// `file:line` of a statement; inside test procedures, the line of the call and the procedure chain.
    fn where_(&self) -> String {
        let line = self.calls.first().map_or(self.test.pos.0, |(_, l)| *l);
        if self.calls.is_empty() {
            format!("{}:{}", self.test.origin, self.test.pos.0)
        } else {
            let chain: Vec<String> = self.calls.iter().map(|(n, _)| n.clone()).collect();
            format!("{}:{line} (in {})", self.test.origin, chain.join(" > "))
        }
    }

    /// The expression with the bound names put in, the design's names resolved (bundle fields, struct members),
    /// and `dut.a.b` as a hierarchical name.
    fn value(&self, e: &Expr) -> Expr {
        let mut e = e.clone();
        for (name, value) in self.binds.iter().rev() {
            e = map_expr(&e, &mut |x| {
                Ok(match x {
                    Expr::Ident(n, _) if n == name => Some(value.clone()),
                    _ => None,
                })
            })
            .unwrap_or(e);
        }
        let e = map_expr(&e, &mut |x| Ok(hier_name(x))).unwrap_or(e);
        let folded = fold_expr(&e, &self.env);
        // an element of a vector of bundles is an index of the vector's merged signal (see elab::vecmerge)
        map_expr(&folded, &mut |x| {
            Ok(match x {
                Expr::Ident(name, pos) => self.env.vec_element(name).map(|(merged, k)| {
                    Expr::Index(Box::new(Expr::Ident(merged, *pos)), Box::new(Expr::Num(k.to_string())))
                }),
                _ => None,
            })
        })
        .unwrap_or(folded)
    }

    fn text(&self, e: &Expr) -> Result<String> {
        expr(&self.value(e), -1, false)
    }

    fn settle(&mut self) {
        if self.dirty {
            self.w("#1;");
            self.dirty = false;
        }
    }

    fn cycles(&mut self, n: i64) {
        if self.clock {
            let clk = &self.clk;
            self.w(&if n == 1 { format!("@(negedge {clk});") } else { format!("repeat ({n}) @(negedge {clk});") });
        } else {
            self.w(&format!("#{};", 10 * n));
        }
        self.dirty = false;
    }

    fn do_reset(&mut self) {
        let Some((name, low)) = self.reset.clone() else { return };
        self.w(&format!("{name} = {};", if low { 0 } else { 1 }));
        self.cycles(2);
        self.w(&format!("{name} = {};", if low { 1 } else { 0 }));
        self.dirty = true;
    }

    fn input(&self, name: &str) -> Option<&Port> {
        self.module.ports.iter().find(|p| p.name == name && p.dir == Dir::Input)
    }

    fn run(&mut self, stmts: &[Stmt]) -> Result<()> {
        let mark = self.binds.len();
        for s in stmts {
            self.stmt(s)?;
        }
        self.binds.truncate(mark);
        Ok(())
    }

    fn stmt(&mut self, s: &Stmt) -> Result<()> {
        match s {
            Stmt::Block(stmts) => self.run(stmts),
            Stmt::Assign { lhs, rhs, .. } => {
                let lhs = self.value(lhs);
                let mut root = &lhs;
                // the input port under a part select, an element or a field of a packed struct (`s.ar.data.addr`)
                while let Expr::Slice(b, ..) | Expr::Index(b, _) | Expr::Member(b, _, _) = root {
                    root = b;
                }
                let Expr::Ident(name, _) = root else {
                    return Err(self.fail("only an input port of the design can be assigned", 0));
                };
                if self.input(name).is_none() {
                    return Err(self.fail(&format!("'{name}' is not an input of '{}': a test drives inputs", self.module.name), 0));
                }
                let text = format!("{} = {};", expr(&lhs, -1, false)?, self.text(rhs)?);
                self.w(&text);
                self.dirty = true;
                Ok(())
            }
            Stmt::Val(name, e) => {
                let v = self.value(e);
                self.binds.push((name.clone(), v));
                Ok(())
            }
            Stmt::For { header, body } => {
                let mut h = header.clone();
                h.lo = self.value(&h.lo);
                h.bound = h.bound.as_ref().map(|b| self.value(b));
                h.step = h.step.as_ref().map(|b| self.value(b));
                // a loop over the rows of a constant table: the index is bound to each row
                if let (None, Expr::List(rows)) = (&h.bound, &h.lo) {
                    for row in rows {
                        self.binds.push((header.var.clone(), row.clone()));
                        self.stmt(body)?;
                        self.binds.pop();
                    }
                    return Ok(());
                }
                let Some(values) = loop_values(&h, &self.env) else {
                    return Err(self.fail("the bounds of a test loop must be constant", 0));
                };
                for v in values {
                    self.binds.push((header.var.clone(), Expr::Num(v.to_string())));
                    self.stmt(body)?;
                    self.binds.pop();
                }
                Ok(())
            }
            Stmt::If { cond, then, els } => {
                let c = self.value(cond);
                if let Some(v) = int_of(&c) {
                    let branch = if v != 0 { Some(&**then) } else { els.as_deref() };
                    return branch.map_or(Ok(()), |b| self.stmt(b));
                }
                self.settle();
                let text = format!("if ({}) begin", expr(&c, -1, false)?);
                self.w(&text);
                self.stmt(then)?;
                if let Some(e) = els {
                    self.w("end else begin");
                    self.stmt(e)?;
                }
                self.w("end");
                Ok(())
            }
            Stmt::ExprStmt(Expr::Call(f, args)) => {
                let Expr::Ident(cmd, pos) = &**f else { return Err(self.fail("a test command is a name", 0)) };
                self.call(cmd, args, pos.0)
            }
            Stmt::ExprStmt(Expr::Ident(cmd, pos)) => self.call(cmd, &[], pos.0),
            _ => Err(self.fail("statement not supported in a test", 0)),
        }
    }

    /// A command of a test, or a call of a test procedure.
    fn call(&mut self, cmd: &str, args: &[Expr], line: usize) -> Result<()> {
        if let Some((params, body)) = self.procs.get(cmd) {
            if params.len() != args.len() {
                return Err(self.fail(&format!("'{cmd}' expects {} argument(s)", params.len()), line));
            }
            if self.calls.len() >= MAX_CALL_DEPTH {
                return Err(self.fail(&format!("test procedures nest too deep (at '{cmd}')"), line));
            }
            let values: Vec<Expr> = args.iter().map(|a| self.value(a)).collect();
            let mark = self.binds.len();
            for (p, v) in params.iter().zip(values) {
                self.binds.push((p.clone(), v));
            }
            self.calls.push((cmd.to_string(), line));
            let body = body.clone();
            let result = self.run(&body);
            self.calls.pop();
            self.binds.truncate(mark);
            return result;
        }
        let place = self.where_();
        if place != self.at {
            self.w(&format!("ovc_at = \"{place}\";"));
            self.at = place.clone();
        }
        match cmd {
            "step" => {
                let n = match args.first() {
                    Some(a) => int_of(&self.value(a)).ok_or_else(|| self.fail("step(n): n must be constant", line))?,
                    None => 1,
                };
                self.cycles(n);
            }
            "reset" if args.is_empty() => self.do_reset(),
            "expect" => {
                let cond = args.first().ok_or_else(|| self.fail("expect(condition[, \"message\"])", line))?;
                self.settle();
                self.check(cond, args.get(1), &place, None)?;
            }
            "wait_until" => {
                let cond = args.first().ok_or_else(|| self.fail("wait_until(condition[, max cycles[, \"message\"]])", line))?;
                let msg = match args.get(2) {
                    Some(Expr::Num(m)) => format!(" {}", m.trim_matches('"')),
                    _ => String::new(),
                };
                self.settle();
                let text = self.text(cond)?;
                let limit = match args.get(1) {
                    Some(l) => int_of(&self.value(l)).ok_or_else(|| self.fail("max cycles must be constant", line))?,
                    None => DEFAULT_TIMEOUT,
                };
                let clk = if self.clock { format!("@(negedge {})", self.clk) } else { "#10".to_string() };
                self.w(&format!("for (int n = 0; n < {limit} && {}; n++) {clk};", not_true(&text)));
                self.w(&format!("if ({}) begin", not_true(&text)));
                self.w(&format!(
                    "  ovc_fails++; $display(\"  FAIL {place} [{}] wait_until({}){msg} not reached in {limit} cycles\");",
                    self.test.name,
                    text.replace('"', "")
                ));
                self.w("end");
            }
            "print" => {
                self.settle();
                let mut parts = Vec::new();
                for a in args {
                    parts.push(self.text(a)?);
                }
                self.w(&format!("$display({}); $fflush;", parts.join(", ")));
            }
            "send" | "recv" => self.stream_command(cmd, args, &place, line)?,
            other => {
                return Err(self.fail(&format!("unknown test command '{other}' (step, reset, expect, wait_until, print, send, recv)"), line));
            }
        }
        Ok(())
    }

    /// The signals `(valid, ready, data)` of the stream named by an argument (`s.aw`).
    fn stream(&self, arg: &Expr, cmd: &str, line: usize) -> Result<(String, String, String)> {
        let folded = self.value(arg);
        let Expr::Ident(p, _) = &folded else {
            return Err(self.fail(&format!("{cmd}(): the first argument is a valid/ready stream of the module (e.g. s.aw)"), line));
        };
        // a stream of an element of a vector of bundles: the field of the merged signal, indexed (see elab::vecmerge)
        let resolve = |leaf: &str| -> (String, String) {
            let element = format!("{p}_{leaf}");
            match self.env.vec_element(&element) {
                Some((merged, k)) => (format!("{merged}[{k}]"), merged),
                None => (element.clone(), element),
            }
        };
        let ((valid, valid_port), (ready, ready_port), (data, data_port)) = (resolve("valid"), resolve("ready"), resolve("data"));
        let driven = if cmd == "send" { &valid_port } else { &ready_port };
        if self.input(driven).is_none() || self.module.ports.iter().all(|q| q.name != data_port) {
            let what = if cmd == "send" { "offers" } else { "takes" };
            return Err(self.fail(&format!("{cmd}({p}): the module {what} values on this stream; use {}()", if cmd == "send" { "recv" } else { "send" }), line));
        }
        Ok((valid, ready, data))
    }

    fn wait_for(&mut self, cond: &str, what: &str, place: &str) {
        let clk = self.clk.clone();
        self.w(&format!("for (int n = 0; n < {DEFAULT_TIMEOUT} && !{cond}; n++) @(negedge {clk});"));
        self.w(&format!("if (!{cond}) begin"));
        self.w(&format!("  ovc_fails++; $display(\"  FAIL {place} [{}] {what}: no transfer in {DEFAULT_TIMEOUT} cycles\");", self.test.name));
        self.w("end");
    }

    fn stream_command(&mut self, cmd: &str, args: &[Expr], place: &str, line: usize) -> Result<()> {
        if !self.clock {
            return Err(self.fail(&format!("{cmd}() needs a clocked module"), line));
        }
        let first = args.first().ok_or_else(|| self.fail(&format!("{cmd}(stream[, ...])"), line))?;
        let shown = show(first);
        let what = format!("{cmd}({shown})");
        let (valid, ready, data) = self.stream(first, cmd, line)?;
        // several streams at once: the address and the data of a write
        if cmd == "send" && args.len() > 1 && matches!(self.value(&args[1]), Expr::Ident(ref n, _) if self.input(&format!("{n}_valid")).is_some()) {
            let mut streams = Vec::new();
            for a in args {
                streams.push(self.stream(a, "send", line)?);
            }
            if streams.len() > 8 {
                return Err(self.fail("send(): at most 8 streams at once", line));
            }
            for (v, _, _) in &streams {
                self.w(&format!("{v} = 1;"));
            }
            self.dirty = true;
            self.settle();
            let pending: Vec<String> = streams.iter().map(|(v, _, _)| v.clone()).collect();
            let pending = pending.join(" || ");
            self.w(&format!("for (int n = 0; n < {DEFAULT_TIMEOUT} && ({pending}); n++) begin"));
            for (k, (v, r, _)) in streams.iter().enumerate() {
                self.w(&format!("  ovc_taken[{k}] = {v} && {r};"));
            }
            let clk = self.clk.clone();
            self.w(&format!("  @(negedge {clk});"));
            for (k, (v, _, _)) in streams.iter().enumerate() {
                self.w(&format!("  if (ovc_taken[{k}]) {v} = 0;"));
            }
            self.w("  #1;");
            self.w("end");
            self.w(&format!("if ({pending}) begin"));
            let all: Vec<String> = args.iter().map(show).collect();
            self.w(&format!(
                "  ovc_fails++; $display(\"  FAIL {place} [{}] send({}): not all taken in {DEFAULT_TIMEOUT} cycles\");",
                self.test.name,
                all.join(", ")
            ));
            self.w("end");
            self.dirty = false;
            return Ok(());
        }
        if cmd == "send" {
            if args.len() > 2 {
                return Err(self.fail("send(stream[, data]) or send(stream, stream, ...)", line));
            }
            if let Some(d) = args.get(1) {
                let text = format!("{data} = {};", self.text(d)?);
                self.w(&text);
            }
            self.w(&format!("{valid} = 1;"));
            self.dirty = true;
            self.settle();
            self.wait_for(&ready, &what, place);
            self.cycles(1);
            self.w(&format!("{valid} = 0;"));
        } else {
            if args.len() > 3 {
                return Err(self.fail("recv(stream[, condition[, \"message\"]])", line));
            }
            self.w(&format!("{ready} = 1;"));
            self.dirty = true;
            self.settle();
            self.wait_for(&valid, &what, place);
            if let Some(c) = args.get(1) {
                self.check(c, args.get(2), place, Some(&what))?;
            }
            self.cycles(1);
            self.w(&format!("{ready} = 0;"));
        }
        self.dirty = true;
        Ok(())
    }

    /// A checked condition: on failure, the test, the line, the condition and the message.
    fn check(&mut self, cond: &Expr, message: Option<&Expr>, place: &str, within: Option<&str>) -> Result<()> {
        let text = self.text(cond)?;
        let msg = match message {
            Some(Expr::Num(m)) => format!(" {}", m.trim_matches('"')),
            _ => String::new(),
        };
        let where_ = within.map(|w| format!("{w}: ")).unwrap_or_default();
        self.w(&format!("if ({}) begin", not_true(&text)));
        self.w(&format!(
            "  ovc_fails++; $display(\"  FAIL {place} [{}] {where_}expect({}){msg}\");",
            self.test.name,
            text.replace('"', "'")
        ));
        self.w("end");
        Ok(())
    }
}

/// `s.aw.data` as written in the source (for messages).
fn show(e: &Expr) -> String {
    match e {
        Expr::Ident(n, _) => n.clone(),
        Expr::Member(b, n, _) => format!("{}.{n}", show(b)),
        Expr::Index(b, i) => match &**i {
            Expr::Num(t) => format!("{}[{t}]", show(b)),
            _ => format!("{}[..]", show(b)),
        },
        _ => "...".into(),
    }
}

/// `dut.a.b` (a path from the design) as one hierarchical name; `None` for anything else.
fn hier_name(e: &Expr) -> Option<Expr> {
    fn path(e: &Expr) -> Option<String> {
        match e {
            Expr::Ident(n, _) => Some(n.clone()),
            Expr::Member(b, n, _) => Some(format!("{}.{n}", path(b)?)),
            Expr::Index(b, i) => match &**i {
                Expr::Num(t) => Some(format!("{}[{t}]", path(b)?)),
                _ => None,
            },
            _ => None,
        }
    }
    match e {
        Expr::Member(..) | Expr::Index(..) => {
            let p = path(e)?;
            p.starts_with("dut.").then_some(Expr::Ident(p, (0, 0)))
        }
        _ => None,
    }
}
